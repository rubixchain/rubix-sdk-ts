import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bytesToHex, hexToBytes } from "@noble/curves/utils.js";
import { describe, expect, test } from "vitest";
import { loadAccountFromFile, saveAccountToFile } from "../../src/crypto/account.js";
import { getSeedFromMnemonic } from "../../src/crypto/bip39.js";
import { Secp256k1Keypair, secp256k1Verify } from "../../src/crypto/secp256k1.js";
import { validateAssetAddress, validateDid } from "../../src/utils/validate.js";

// Generated by scripts/generate_python_vectors.py from the reference Python SDK
const fixturesDir = join(dirname(fileURLToPath(import.meta.url)), "..", "fixtures", "python");
const vectors = JSON.parse(readFileSync(join(fixturesDir, "vectors.json"), "utf-8"));

describe("compatibility with the Python SDK", () => {
  test("derives the same seed and keypair from a mnemonic", () => {
    const seed = getSeedFromMnemonic(vectors.mnemonic);
    expect(bytesToHex(seed)).toBe(vectors.seed);

    const keypair = Secp256k1Keypair.fromMnemonicSeed(seed);
    expect(keypair.privateKey).toBe(vectors.seedKeypair.privateKey);
    expect(keypair.publicKey).toBe(vectors.seedKeypair.publicKey);
  });

  test("derives the same public key from a private key", () => {
    const keypair = Secp256k1Keypair.fromPrivateKey(hexToBytes(vectors.privateKeyKeypair.privateKey));
    expect(keypair.privateKey).toBe(vectors.privateKeyKeypair.privateKey);
    expect(keypair.publicKey).toBe(vectors.privateKeyKeypair.publicKey);
  });

  test.each(vectors.signatures as any[])(
    "verifies Python signature (message $message, highS $highS) like Python does",
    (vector) => {
      const publicKey = hexToBytes(vectors.privateKeyKeypair.publicKey);
      const message = hexToBytes(vector.message);
      const signature = hexToBytes(vector.signature);

      expect(secp256k1Verify(publicKey, message, signature)).toBe(vector.valid);
      const otherMessage = new Uint8Array([...message, ...new TextEncoder().encode("x")]);
      expect(secp256k1Verify(publicKey, otherMessage, signature)).toBe(vector.validForOtherMessage);
    },
  );

  test("signs messages that verify under the same rules as Python", () => {
    const keypair = Secp256k1Keypair.fromPrivateKey(hexToBytes(vectors.privateKeyKeypair.privateKey));
    const publicKey = hexToBytes(keypair.publicKey);
    for (const vector of vectors.signatures) {
      const message = hexToBytes(vector.message);
      const signature = keypair.sign(message);
      expect(secp256k1Verify(publicKey, message, signature)).toBe(true);
      // Messages longer than 32 bytes are truncated to their leftmost 256 bits before signing
      const otherMessage = new Uint8Array([...message, 0x78]);
      expect(secp256k1Verify(publicKey, otherMessage, signature)).toBe(vector.validForOtherMessage);
    }
  });

  test("loads an account saved by the Python SDK", async () => {
    const { account } = vectors;
    const loaded = await loadAccountFromFile(join(fixturesDir, account.dir), account.alias, account.passphrase);
    expect(loaded.did).toBe(account.did);
    expect(loaded.keypair.publicKey).toBe(account.publicKey);
    expect(loaded.keypair.privateKey).toBe(account.privateKey);
  });

  test.each(vectors.cids as any[])("validates CID $value like Python does", ({ value, isDid, isAssetAddress }) => {
    expect(validateDid(value)).toBe(isDid);
    expect(validateAssetAddress(value)).toBe(isAssetAddress);
  });

  // Requires a Python interpreter with rubix-py installed, e.g. RUBIX_PYTHON=/path/to/venv/bin/python
  test.skipIf(!process.env.RUBIX_PYTHON)("Python SDK loads accounts and verifies signatures made by the TS SDK", async () => {
    const accountDir = await mkdtemp(join(tmpdir(), "rubix-sdk-ts-compat-"));
    try {
      const keypair = Secp256k1Keypair.fromMnemonicSeed(getSeedFromMnemonic(vectors.mnemonic));
      const did = "bafybmicbopex4ydytrtremmculwpo7e5p2uvbkuw2ds775xmkcsc5lglai";
      await saveAccountToFile(accountDir, hexToBytes(keypair.publicKey), hexToBytes(keypair.privateKey), did, "ts", "tspass");

      const signatures = vectors.signatures.map((v: any) => ({
        message: v.message,
        signature: bytesToHex(keypair.sign(hexToBytes(v.message))),
      }));

      const script = `
import json, sys
from rubix.crypto.account import load_account_from_file
from rubix.crypto.secp256k1 import secp256k1_verify
account = load_account_from_file(sys.argv[1], "ts", passphrase="tspass")
sigs = json.loads(sys.argv[2])
print(json.dumps({
    "did": account.did,
    "publicKey": account.keypair.public_key,
    "privateKey": account.keypair.private_key,
    "valid": [secp256k1_verify(bytes.fromhex(account.keypair.public_key), bytes.fromhex(s["message"]), bytes.fromhex(s["signature"])) for s in sigs],
}))
`;
      const output = execFileSync(process.env.RUBIX_PYTHON!, ["-I", "-c", script, accountDir, JSON.stringify(signatures)], {
        encoding: "utf-8",
      });
      const result = JSON.parse(output);

      expect(result.did).toBe(did);
      expect(result.publicKey).toBe(keypair.publicKey);
      expect(result.privateKey).toBe(keypair.privateKey);
      expect(result.valid).toEqual(signatures.map(() => true));
    } finally {
      await rm(accountDir, { recursive: true, force: true });
    }
  });
});
